export type I18nKey = keyof typeof fr;

const dictionaries: Record<Locale, Record<I18nKey, string>> = {
  fr: fr as Record<I18nKey, string>,
  en,
};

export function t(locale: Locale, key: I18nKey): string {
  return dictionaries[locale]?.[key] ?? dictionaries.fr[key] ?? key;
}

export function actionLabel(locale: Locale, action: PowerAction): string {
  switch (action) {
    case "shutdown":
      return t(locale, "actionShutdown");
    case "restart":
      return t(locale, "actionRestart");
    case "sleep":
      return t(locale, "actionSleep");
    case "hibernate":
      return t(locale, "actionHibernate");
    case "lock":
      return t(locale, "actionLock");
  }
}

export function dayLabel(locale: Locale, index: number): string {
  const keys: I18nKey[] = [
    "dayMon",
    "dayTue",
    "dayWed",
    "dayThu",
    "dayFri",
    "daySat",
    "daySun",
  ];
  return t(locale, keys[index] ?? "dayMon");
}
